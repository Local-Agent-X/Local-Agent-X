#!/usr/bin/env node
// Regenerate THIRD_PARTY_NOTICES.md from the vendor skill packs' pack.json
// files, so the notice always matches what ships in src/protocols/bundled/vendor.
//   node scripts/write-skill-notices.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const VENDOR = join(ROOT, "src", "protocols", "bundled", "vendor");

const packs = readdirSync(VENDOR)
  .filter((v) => existsSync(join(VENDOR, v, "pack.json")))
  .map((v) => JSON.parse(readFileSync(join(VENDOR, v, "pack.json"), "utf8")));

let out = `# Third-party notices

Local Agent X ships official Agent Skills from the platforms below, copied
without modification from each vendor's repository at the pinned commit, under
\`src/protocols/bundled/vendor/<vendor>/\`. Each folder keeps the vendor's
LICENSE (and NOTICE, where the repository has one). These skills remain under
their own licenses; the Local Agent X license covers only Local Agent X's own
work. LAX adds a \`pack.json\` beside each pack (source, commit, docs link, CLI
names, project markers) and edits no vendor file.

This file is generated by \`scripts/write-skill-notices.mjs\` from those pack.json files.

`;

for (const p of packs) {
  out += `## ${p.vendor}\n\n- Source: ${p.repo} @ \`${p.commit}\` (pinned ${p.pinnedAt})\n- License: ${p.license} — see \`src/protocols/bundled/vendor/${p.vendor}/LICENSE\`\n`;
  const skills = Object.entries(p.skills);
  const lax = skills.filter(([, s]) => s.license === "LAX").map(([k]) => k);
  out += `- Skills: ${skills.filter(([, s]) => s.license !== "LAX").map(([k]) => `\`${k}\``).join(", ")}\n`;
  if (lax.length) out += `- Written for Local Agent X, not from this repository: ${lax.map((k) => `\`${k}\``).join(", ")} (from the vendor's public documentation)\n`;
  const notice = join(VENDOR, p.vendor, "NOTICE");
  if (existsSync(notice)) out += `\nNOTICE from ${p.repo}:\n\n\`\`\`\n${readFileSync(notice, "utf8").trim()}\n\`\`\`\n`;
  out += "\n";
}

writeFileSync(join(ROOT, "THIRD_PARTY_NOTICES.md"), out);
console.log(`THIRD_PARTY_NOTICES.md: ${packs.length} packs`);
