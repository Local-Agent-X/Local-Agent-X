import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { Op } from "../ops/types.js";
import type { ToolCallContext } from "./context.js";
import { claimClashGate, recordWrittenClaims, _resetClaimClashGateForTest } from "./claim-clash-gate.js";
import { findClashes, recordClaims, _resetWorkClaimsForTest, _setWorkClaimsForTest } from "../agency/work-claims.js";
import { _resetHandoverNotesForTest, _setHandoverNotesForTest } from "../agency/handover-notes.js";
import { _resetRepoLocateCacheForTest } from "../agency/repo-locate.js";
import { _resetTreeChangesForTest } from "../agency/tree-changes.js";
import { clearSessionWorkRoot, setSessionWorkRoot } from "../workspace/paths.js";

let repo: string;
const g = (...args: string[]) =>
  execFileSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", ...args], { cwd: repo, encoding: "utf8" });

function shell(sessionId: string, command: string): ToolCallContext {
  return { tc: { id: "t", name: "bash", arguments: "{}" }, args: { command }, sessionId, operationId: `op-${sessionId}` } as unknown as ToolCallContext;
}

beforeEach(() => {
  const root = mkdtempSync(join(tmpdir(), "lax-shell-claims-"));
  repo = join(root, "repo");
  execFileSync("git", ["init", "-q", "-b", "main", repo]);
  writeFileSync(join(repo, "gen.ts"), "old\n");
  writeFileSync(join(repo, "dirty-before.ts"), "v1\n");
  g("add", "-A"); g("commit", "-q", "-m", "base");
  writeFileSync(join(repo, "dirty-before.ts"), "v2 — edited before the agent ran anything\n");
  _resetRepoLocateCacheForTest(); _resetClaimClashGateForTest(); _resetTreeChangesForTest();
  _setWorkClaimsForTest({ dir: join(root, "holders"), readOp: (id) => ({ id, lane: "interactive", status: "running", task: `task ${id}`, canonical: { leaseExpiresAt: new Date(Date.now() + 60_000).toISOString() } }) as unknown as Op });
  _setHandoverNotesForTest({ dir: join(root, "notes") });
  setSessionWorkRoot("chat-me", repo);
});
afterEach(() => { clearSessionWorkRoot("chat-me"); _resetWorkClaimsForTest(); _resetHandoverNotesForTest(); });

describe("files a shell command changes without naming them", () => {
  it("become the session's claims, and what was already dirty does not", () => {
    const ctx = shell("chat-me", "npm run codegen");
    claimClashGate(ctx);
    writeFileSync(join(repo, "gen.ts"), "regenerated by the command\n");
    writeFileSync(join(repo, "made.ts"), "new file the command wrote\n");
    recordWrittenClaims(ctx, { content: "done" });

    expect(findClashes("chat-other", [join(repo, "gen.ts")]).map((c) => c.other.sessionId)).toEqual(["chat-me"]);
    expect(findClashes("chat-other", [join(repo, "made.ts")])).toHaveLength(1);
    expect(findClashes("chat-other", [join(repo, "dirty-before.ts")])).toEqual([]);
  });

  it("says so on the result when the file was in another agent's work", () => {
    recordClaims({ sessionId: "chat-other", opId: "op-other", paths: [join(repo, "gen.ts")], source: "written", displayName: "Codegen chat" });
    const ctx = shell("chat-me", "npm run codegen");
    claimClashGate(ctx);
    expect(ctx.coordinationNote).toBeUndefined();
    writeFileSync(join(repo, "gen.ts"), "regenerated\n");
    recordWrittenClaims(ctx, { content: "done" });
    expect(ctx.coordinationNote).toContain("A file this call changed is in another agent's work");
    expect(ctx.coordinationNote).toContain("`gen.ts` is also being changed by **Codegen chat**");
  });

  it("a command that changed nothing claims nothing", () => {
    const ctx = shell("chat-me", "git status");
    claimClashGate(ctx);
    recordWrittenClaims(ctx, { content: "clean" });
    expect(findClashes("chat-other", [join(repo, "gen.ts")])).toEqual([]);
  });
});

describe("two chats in one folder are each credited only with their own changes", () => {
  const holdersOf = (path: string) => findClashes("chat-third", [join(repo, path)]).map((c) => c.other.sessionId).sort();

  it("a file the other chat edited while this chat's command ran stays the other chat's", () => {
    const ctx = shell("chat-me", "npm run build");
    claimClashGate(ctx);
    // While the command runs: the other chat edits a file with its edit tool,
    // and the command itself regenerates another.
    writeFileSync(join(repo, "theirs.ts"), "the other chat's edit\n");
    recordClaims({ sessionId: "chat-other", opId: "op-other", paths: [join(repo, "theirs.ts")], source: "written" });
    writeFileSync(join(repo, "gen.ts"), "regenerated by my command\n");
    recordWrittenClaims(ctx, { content: "done" });

    expect(holdersOf("theirs.ts")).toEqual(["chat-other"]);
    expect(holdersOf("gen.ts")).toEqual(["chat-me"]);
  });

  it("what changed in the folder between this chat's commands is not credited to its next one", () => {
    const first = shell("chat-me", "ls");
    claimClashGate(first);
    recordWrittenClaims(first, { content: "" });
    // Someone else changes a file, by a route that left no claim at all.
    writeFileSync(join(repo, "gen.ts"), "changed by someone else, unseen\n");
    const second = shell("chat-me", "ls");
    claimClashGate(second);
    recordWrittenClaims(second, { content: "" });
    expect(holdersOf("gen.ts")).toEqual([]);
  });

  it("a file this chat then changes itself becomes its own again", () => {
    writeFileSync(join(repo, "gen.ts"), "the other chat's version\n");
    recordClaims({ sessionId: "chat-other", opId: "op-other", paths: [join(repo, "gen.ts")], source: "written" });
    const ctx = shell("chat-me", "npm run codegen");
    claimClashGate(ctx);
    writeFileSync(join(repo, "gen.ts"), "now regenerated by my command, longer\n");
    recordWrittenClaims(ctx, { content: "done" });
    expect(holdersOf("gen.ts")).toEqual(["chat-me", "chat-other"]);
  });
});
